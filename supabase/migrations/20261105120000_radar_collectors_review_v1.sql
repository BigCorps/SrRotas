-- Sr. Rotas Radar — credenciais por coletor externo + revisão humana de eventos (v1, vc110)
-- ESTRITAMENTE ADITIVA e idempotente: create table if not exists / add column if not exists /
-- constraints guardadas. Nenhuma linha existente muda de semântica:
--   * sr_event_opportunities.review_status nasce com default 'approved', portanto Ticketmaster,
--     ingest interno (RADAR_INGEST_SECRET) e admin manual seguem visíveis exatamente como hoje;
--   * somente o caminho de coletor externo grava 'pending'.
-- Server-only: RLS habilitado, sem policy para anon/authenticated, acesso apenas via service_role.
-- Rollback (NÃO executar automaticamente) no fim do arquivo, em comentários.
begin;

-- 1. Coletores (uma credencial por agente externo). A chave em texto puro NUNCA é armazenada.
create table if not exists public.sr_radar_collectors (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  status text not null default 'active',
  allowed_sources text[] not null default '{}'::text[],
  scopes text[] not null default array['events:ingest']::text[],
  key_prefix text not null,
  key_hash text not null,
  max_batch integer not null default 200,
  rate_limit_per_hour integer not null default 30,
  created_at timestamptz not null default now(),
  created_by text,
  rotated_at timestamptz,
  rotated_by text,
  revoked_at timestamptz,
  revoked_by text,
  updated_at timestamptz not null default now(),
  last_used_at timestamptz
);

do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'sr_radar_collectors_status_chk') then
    alter table public.sr_radar_collectors
      add constraint sr_radar_collectors_status_chk check (status in ('active','revoked'));
  end if;
  if not exists (select 1 from pg_constraint where conname = 'sr_radar_collectors_scopes_chk') then
    alter table public.sr_radar_collectors
      add constraint sr_radar_collectors_scopes_chk
      check (scopes <@ array['events:ingest','pois:propose']::text[]);
  end if;
  if not exists (select 1 from pg_constraint where conname = 'sr_radar_collectors_max_batch_chk') then
    alter table public.sr_radar_collectors
      add constraint sr_radar_collectors_max_batch_chk check (max_batch between 1 and 500);
  end if;
  if not exists (select 1 from pg_constraint where conname = 'sr_radar_collectors_rate_chk') then
    alter table public.sr_radar_collectors
      add constraint sr_radar_collectors_rate_chk check (rate_limit_per_hour between 1 and 1000);
  end if;
  if not exists (select 1 from pg_constraint where conname = 'sr_radar_collectors_key_hash_chk') then
    alter table public.sr_radar_collectors
      add constraint sr_radar_collectors_key_hash_chk check (key_hash ~ '^[0-9a-f]{64}$');
  end if;
end $$;

create unique index if not exists sr_radar_collectors_key_hash_uidx
  on public.sr_radar_collectors(key_hash);
create index if not exists sr_radar_collectors_status_idx
  on public.sr_radar_collectors(status);

-- 2. Auditoria de uso (sem payload, sem IP bruto).
create table if not exists public.sr_radar_collector_usage (
  id bigint generated by default as identity primary key,
  collector_id uuid not null references public.sr_radar_collectors(id) on delete cascade,
  at timestamptz not null default now(),
  endpoint text not null,
  http_status integer not null,
  received integer not null default 0,
  accepted integer not null default 0,
  rejected integer not null default 0,
  run_id text,
  ip_hash text
);
create index if not exists sr_radar_collector_usage_collector_at_idx
  on public.sr_radar_collector_usage(collector_id, at desc);

-- 3. Revisão humana dos eventos (aditivo; default mantém o comportamento atual).
alter table public.sr_event_opportunities
  add column if not exists review_status text not null default 'approved',
  add column if not exists collector_id uuid references public.sr_radar_collectors(id) on delete set null,
  add column if not exists ingest_run_id text,
  add column if not exists review_note text,
  add column if not exists reviewed_at timestamptz,
  add column if not exists reviewed_by text,
  add column if not exists first_seen_at timestamptz default now();

do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'sr_event_opportunities_review_status_chk') then
    alter table public.sr_event_opportunities
      add constraint sr_event_opportunities_review_status_chk
      check (review_status in ('pending','approved','rejected','changes_requested'));
  end if;
end $$;

create index if not exists sr_event_opportunities_review_status_idx
  on public.sr_event_opportunities(review_status, status);
create index if not exists sr_event_opportunities_collector_idx
  on public.sr_event_opportunities(collector_id, first_seen_at desc)
  where collector_id is not null;

-- 4. Execuções por coletor/run_id (idempotência de reenvio).
alter table public.sr_radar_source_runs
  add column if not exists collector_id uuid references public.sr_radar_collectors(id) on delete set null,
  add column if not exists run_id text,
  add column if not exists rejected_count integer not null default 0,
  add column if not exists expired_count integer not null default 0,
  add column if not exists summary jsonb;

create unique index if not exists sr_radar_source_runs_collector_run_uidx
  on public.sr_radar_source_runs(collector_id, run_id)
  where collector_id is not null and run_id is not null;
create index if not exists sr_radar_source_runs_collector_created_idx
  on public.sr_radar_source_runs(collector_id, created_at desc)
  where collector_id is not null;

-- 5. Log de decisões de revisão (eventos e lugares).
create table if not exists public.sr_radar_review_decisions (
  id uuid primary key default gen_random_uuid(),
  target_type text not null,
  target_id uuid not null,
  decision text not null,
  note text,
  actor_email text not null,
  previous_status text,
  created_at timestamptz not null default now()
);

do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'sr_radar_review_decisions_target_chk') then
    alter table public.sr_radar_review_decisions
      add constraint sr_radar_review_decisions_target_chk check (target_type in ('event','poi'));
  end if;
  if not exists (select 1 from pg_constraint where conname = 'sr_radar_review_decisions_decision_chk') then
    alter table public.sr_radar_review_decisions
      add constraint sr_radar_review_decisions_decision_chk
      check (decision in ('approve','reject','request_changes'));
  end if;
end $$;

create index if not exists sr_radar_review_decisions_target_idx
  on public.sr_radar_review_decisions(target_type, target_id, created_at desc);
create index if not exists sr_radar_review_decisions_created_idx
  on public.sr_radar_review_decisions(created_at desc);

-- 6. Segurança: server-only.
alter table public.sr_radar_collectors enable row level security;
alter table public.sr_radar_collector_usage enable row level security;
alter table public.sr_radar_review_decisions enable row level security;

revoke all on table public.sr_radar_collectors from public, anon, authenticated;
revoke all on table public.sr_radar_collector_usage from public, anon, authenticated;
revoke all on table public.sr_radar_review_decisions from public, anon, authenticated;
grant select, insert, update, delete on table public.sr_radar_collectors to service_role;
grant select, insert, update, delete on table public.sr_radar_collector_usage to service_role;
grant select, insert, update, delete on table public.sr_radar_review_decisions to service_role;
grant usage, select on sequence public.sr_radar_collector_usage_id_seq to service_role;

comment on table public.sr_radar_collectors is
  'Credenciais de coletores externos do Radar. key_hash = SHA-256 hex da chave completa; a chave em texto nunca é persistida.';
comment on table public.sr_radar_collector_usage is
  'Auditoria de uso por coletor: endpoint, status HTTP e contagens. Sem payload e sem IP bruto (ip_hash truncado).';
comment on column public.sr_event_opportunities.review_status is
  'pending|approved|rejected|changes_requested. Consumidores do app só leem approved. Default approved preserva fontes internas.';
comment on table public.sr_radar_review_decisions is
  'Decisões humanas de revisão do Radar (eventos e lugares) com autor e status anterior.';

commit;

